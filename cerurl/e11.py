"""E11: executed local HTTP cloaking experiment with sealed policy inputs.

The site label means 'has a latent simulated marker in the declared experiment
window', including unavailable states. It is never generated by a model.
Policies see only acquired observations and the public condition inventory.
CER is a counterfactual acquisition heuristic using core.certify on a one-node
witness model; its certificate is NOT a guarantee about unseen website content.
"""
from __future__ import annotations

from dataclasses import asdict
from contextlib import closing
from http.client import HTTPConnection
import csv
import json
from pathlib import Path
import random
import time

import numpy as np

from .core import Case, Observation, certify
from .e11_testbed import (
    ACTIONS, COLLECTORS, COLLECTOR_MAP, MARKER, SCENARIOS, SLOT_SECONDS, SLOTS,
    Action, Testbed, canon, classify, collect, digest, make_sites, site_state,
)


POLICIES = ("one_vantage", "fixed_three", "random_new", "diversity", "cer_challenge")


def decision(observations: list[dict]) -> str:
    values = {o["observed"] for o in observations if o["available"]}
    if "malicious" in values:
        return "malicious"
    return "benign" if "benign" in values else "abstain"


def witness_certificate(observations: list[dict]) -> dict | None:
    valid = [o for o in observations if o["available"]]
    if not valid:
        return None
    obs = [Observation(0, float(o["observed"] == "malicious"), 1 / len(valid),
                       frozenset(o["source_ancestors"]), str(i)) for i, o in enumerate(valid)]
    return certify(Case("e11-challenge-surrogate", np.eye(1), obs, 0), budget=1, alpha=0)


def novelty(action: Action, history: list[dict]) -> float:
    c = COLLECTOR_MAP[action.collector_id]
    # Attempts count here, even when unavailable: a failed attempt must not make
    # its identical condition appear perpetually new to the acquisition policy.
    roots = {r for o in history for r in o["source_ancestors"]}
    return (2 * float(not roots.intersection(c.ancestors))
            + float(c.ua_family not in {o["ua_family"] for o in history})
            + float(c.network not in {o["network"] for o in history})
            + .5 * float(action.slot not in {o["slot"] for o in history}))


def challenge_score(action: Action, history: list[dict], current: dict | None) -> float:
    """Predeclared 50/50 hypothetical outcomes; no learned or hidden labels.

    Rank source-root interval shrinkage and changes in the surrogate verdict,
    plus condition novelty, per acquisition/wait cost. This is a heuristic.
    """
    c = COLLECTOR_MAP[action.collector_id]
    width = current["upper_bound"] - current["lower_bound"] if current else 1.0
    gain = 0.0
    for value in ("benign", "malicious"):
        hypothetical = {"available": True, "observed": value, "source_ancestors": c.ancestors}
        report = witness_certificate(history + [hypothetical])
        gain += .5 * (width - (report["upper_bound"] - report["lower_bound"])
                       + float(current is not None and report["verdict"] != current["verdict"]))
    wait_slots = max(0, action.slot - history[-1]["slot"])
    return (gain + novelty(action, history)) / (action.cost + .25 * wait_slots)


def select_action(policy: str, history: list[dict], remaining: float, rng: random.Random,
                  actions: tuple[Action, ...] = ACTIONS) -> tuple[Action | None, dict]:
    """Selection accepts ONLY public actions and acquired observations."""
    if policy not in POLICIES:
        raise ValueError(f"Unknown policy {policy}")
    used = {o["action_id"] for o in history}
    slot = history[-1]["slot"] if history else 0
    valid = [a for a in actions if a.action_id not in used and a.slot >= slot and a.cost <= remaining]
    if not history:
        first = next((a for a in valid if a.action_id == "correlated_a@0"), None)
        return first, {"reason": "common_initial_collection"}
    if policy == "one_vantage" or not valid:
        return None, {"reason": "policy_limit_or_budget"}
    if policy == "fixed_three":
        order = ("correlated_b@0", "desktop_independent@0")
        chosen = next((a for name in order for a in valid if a.action_id == name), None)
        return chosen, {"reason": "fixed_three_condition_plan"}
    if policy == "random_new":
        seen_collectors = {o["collector_id"] for o in history}
        fresh = [a for a in valid if a.collector_id not in seen_collectors]
        return (rng.choice(fresh) if fresh else None), {"reason": "uniform_unseen_collector_slot"}
    current = witness_certificate(history) if policy == "cer_challenge" else None
    ranks = [(challenge_score(a, history, current) if policy == "cer_challenge" else novelty(a, history), a)
             for a in valid]
    # Earliest slot and registry order break ties deterministically.
    score, chosen = max(ranks, key=lambda item: (item[0], -item[1].slot, -actions.index(item[1])))
    return chosen, {"reason": policy, "score": score,
                    "witness_certificate_before": current,
                    "certificate_scope": "fixed collected-witness surrogate only" if current else None}


def run_trial(port: int, host: str, policy: str, budget: int, seed: int, artifact_dir: Path,
              connection: HTTPConnection | None = None) -> list[dict]:
    history = []
    rng = random.Random(seed)
    remaining, finish = float(budget), 0.0
    while remaining >= 1:
        action, selection = select_action(policy, history, remaining, rng)
        if action is None:
            break
        request_id = f"{host[:-5]}:{policy}:b{budget}:{len(history)}"
        obs = collect(port, host, action, request_id, artifact_dir, connection)
        finish = max(finish, action.slot * SLOT_SECONDS) + 1.0
        obs.update(policy=policy, budget=budget, step=len(history), selection=selection,
                   modeled_evidence_at_s=finish, decision_before=decision(history))
        history.append(obs)
        obs["decision_after"] = decision(history)
        remaining -= action.cost
    return history


def _write_jsonl(path: Path, rows: list[dict]):
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, sort_keys=True, allow_nan=False) + "\n")


def _write_csv(path: Path, rows: list[dict]):
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def _rate(num: int, den: int) -> float | None:
    return num / den if den else None


def _percentile(values: list[float], p: int) -> float | None:
    return float(np.percentile(values, p)) if values else None


def evaluate_trial(site, history: list[dict], truth: dict[str, dict], policy: str, budget: int) -> tuple[dict, list[dict]]:
    """Join sealed trial results to independently recorded server truth AFTER selection."""
    cells = list(truth.values())
    positive = any(c["latent_state"] == MARKER for c in cells)
    cloaked = any({c["latent_state"] for c in cells if c["slot"] == slot} == {MARKER, "benign"} for slot in SLOTS)
    opportunity = any({c["served_state"] for c in cells if c["slot"] == slot and c["measured_available"]}
                      >= {MARKER, "benign"} for slot in SLOTS)
    markers = [o for o in history if o["observed"] == "malicious" and o["available"]]
    pairs = []
    temporal_changes = 0
    hash_differences = 0
    for i, left in enumerate(history):
        for right in history[i + 1:]:
            if not left["available"] or not right["available"]:
                continue
            hash_differences += left["body_sha256"] != right["body_sha256"]
            if left["observed"] == right["observed"]:
                continue
            if left["slot"] != right["slot"]:
                temporal_changes += 1
                continue
            a, b = truth[left["action_id"]], truth[right["action_id"]]
            actual = (a["measured_available"] and b["measured_available"]
                      and {a["served_state"], b["served_state"]} == {MARKER, "benign"})
            pairs.append({"site_id": site.site_id, "policy": policy, "budget": budget,
                          "left_observation": left["observation_id"], "right_observation": right["observation_id"],
                          "slot": left["slot"], "true_contradiction": actual,
                          "disjoint_source_ancestors": not set(left["source_ancestors"]).intersection(right["source_ancestors"]),
                          "left_sha256": left["body_sha256"], "right_sha256": right["body_sha256"]})
    expected = "malicious" if positive else "benign"
    initial, final = decision(history[:1]), decision(history)
    total_cost = sum(o["acquisition_cost"] for o in history)
    row = {"site_id": site.site_id, "scenario": site.scenario, "policy": policy, "budget": budget,
           "truth": expected, "cloaked": cloaked, "available_cloaking_opportunity": opportunity,
           "marker_available_in_grid": any(c["measured_available"] and c["served_state"] == MARKER for c in cells),
           "available_grid_cells": sum(c["measured_available"] for c in cells),
           "grid_cells": len(cells), "initial_decision": initial, "final_decision": final,
           "marker_discovered": bool(markers), "cloaking_exposed": cloaked and bool(markers),
           "true_contradiction_pairs": sum(p["true_contradiction"] for p in pairs),
           "false_contradiction_pairs": sum(not p["true_contradiction"] for p in pairs),
           "independent_true_contradiction_pairs": sum(p["true_contradiction"] and p["disjoint_source_ancestors"] for p in pairs),
           "temporal_semantic_changes": temporal_changes, "hash_difference_pairs": hash_differences,
           "repair_eligible": initial != expected, "repair_success": initial != expected and final == expected,
           "decision_changed": initial != final, "decision_transitions": sum(o["decision_before"] != o["decision_after"] for o in history[1:]),
           "degraded": initial == expected and final != expected,
           "false_positive": not positive and final == "malicious", "correct_final": final == expected,
           "time_to_evidence_s": markers[0]["modeled_evidence_at_s"] if markers else None,
           "time_to_evidence_wall_ms": sum(o["wall_latency_ms"] for o in history[:history.index(markers[0]) + 1]) if markers else None,
           "evidence_censored": positive and not markers,
           "followup_end_s": history[-1]["modeled_evidence_at_s"] if history else 0,
           "attempts": len(history), "missing_observations": sum(not o["available"] for o in history),
           "available_observations": sum(o["available"] for o in history),
           "total_cost": total_cost, "unused_budget": budget - total_cost,
           "http_requests": sum(o["http_requests"] for o in history),
           "response_bytes": sum(o["response_bytes"] for o in history),
           "collection_wall_ms": sum(o["wall_latency_ms"] for o in history)}
    return row, pairs


def summarize(rows: list[dict]) -> dict:
    n = len(rows)
    cloaked = [r for r in rows if r["cloaked"]]
    opportunity = [r for r in cloaked if r["available_cloaking_opportunity"]]
    benign = [r for r in rows if r["truth"] == "benign"]
    eligible = [r for r in rows if r["repair_eligible"]]
    times = [r["time_to_evidence_s"] for r in rows if r["time_to_evidence_s"] is not None]
    return {"sites": n, "cloaked_sites": len(cloaked), "exposed_sites": sum(r["cloaking_exposed"] for r in cloaked),
            "cloaking_exposure_rate": _rate(sum(r["cloaking_exposed"] for r in cloaked), len(cloaked)),
            "available_opportunity_sites": len(opportunity),
            "exposure_rate_given_available_opportunity": _rate(sum(r["cloaking_exposed"] for r in opportunity), len(opportunity)),
            "true_contradiction_sites": sum(r["true_contradiction_pairs"] > 0 for r in rows),
            "true_contradiction_pairs": sum(r["true_contradiction_pairs"] for r in rows),
            "false_contradiction_pairs": sum(r["false_contradiction_pairs"] for r in rows),
            "repair_eligible": len(eligible), "repair_successes": sum(r["repair_success"] for r in rows),
            "repair_success_rate": _rate(sum(r["repair_success"] for r in eligible), len(eligible)),
            "decision_changes": sum(r["decision_changed"] for r in rows), "degradations": sum(r["degraded"] for r in rows),
            "benign_sites": len(benign), "false_positives": sum(r["false_positive"] for r in benign),
            "false_positive_rate": _rate(sum(r["false_positive"] for r in benign), len(benign)),
            "correct_final_rate": _rate(sum(r["correct_final"] for r in rows), n),
            "abstentions": sum(r["final_decision"] == "abstain" for r in rows),
            "evidence_discoveries": len(times), "positive_sites_without_evidence": sum(r["evidence_censored"] for r in rows),
            "time_to_evidence_detected_p50_s": _percentile(times, 50),
            "time_to_evidence_detected_p95_s": _percentile(times, 95),
            "mean_cost": sum(r["total_cost"] for r in rows) / n,
            "mean_attempts": sum(r["attempts"] for r in rows) / n,
            "missing_observations": sum(r["missing_observations"] for r in rows),
            "http_requests": sum(r["http_requests"] for r in rows),
            "collection_wall_p50_ms": _percentile([r["collection_wall_ms"] for r in rows], 50)}


def validate_observations(observations: list[dict], server_log: list[dict], artifact_dir: Path) -> list[str]:
    errors = []
    served = {r["request_id"]: r for r in server_log}
    for o in observations:
        oid = o["observation_id"]
        collector = COLLECTOR_MAP[o["collector_id"]]
        if (o["source_ancestors"] != list(collector.ancestors)
                or o["network"] != collector.network or o["user_agent"] != collector.user_agent
                or o["action_id"] != f"{collector.collector_id}@{o['slot']}"):
            errors.append(f"{oid}:condition_or_ancestry")
        if o["redirect_chain_sha256"] != digest(canon(o["redirect_chain"])):
            errors.append(f"{oid}:redirect_hash")
        for hop in o["redirect_chain"]:
            record = served.get(hop["request_id"])
            if record is None or any(record[k] != hop[k] for k in ("body_sha256", "status", "location")):
                errors.append(f"{oid}:server_receipt")
            if record and any(record[k] != o[k] for k in ("site_id", "user_agent", "network", "slot")):
                errors.append(f"{oid}:server_condition")
            artifact = artifact_dir / f"{hop['body_sha256']}.html"
            if not artifact.exists() or digest(artifact.read_bytes()) != hop["body_sha256"]:
                errors.append(f"{oid}:artifact_hash")
        if o["redirect_chain"]:
            record = served.get(o["redirect_chain"][-1]["request_id"])
            if o["body_sha256"] != o["redirect_chain"][-1]["body_sha256"]:
                errors.append(f"{oid}:final_body_hash")
            if record and o["available"]:
                expected = "malicious" if record["served_state"] == MARKER else "benign"
                if not record["available"] or o["observed"] != expected or o["status"] != 200:
                    errors.append(f"{oid}:truth_disagrees")
                final_artifact = artifact_dir / f"{o['body_sha256']}.html"
                if final_artifact.exists() and classify(final_artifact.read_bytes(), o["status"]) != o["observed"]:
                    errors.append(f"{oid}:parsed_artifact_disagrees")
        elif o["available"]:
            errors.append(f"{oid}:available_without_response")
        if not o["available"] and o["observed"] is not None:
            errors.append(f"{oid}:missing_used_as_evidence")
    return errors


def run_e11(out_dir="results/E11", table_dir="tables", n_per=20, seed=20261111,
            budgets=(1, 3, 5), plots=True) -> dict:
    if not budgets or any(type(b) is not int or b < 1 or b > len(ACTIONS) for b in budgets) or len(set(budgets)) != len(budgets):
        raise ValueError(f"budgets must be distinct integers in [1, {len(ACTIONS)}]")
    sites = make_sites(n_per, seed)
    started = time.perf_counter()
    out, tables = Path(out_dir), Path(table_dir)
    out.mkdir(parents=True, exist_ok=True)
    tables.mkdir(parents=True, exist_ok=True)
    # A failed or interrupted rerun cannot leave an older success claim/plot.
    for path in (out / "audit.json", out / "manifest_sha256.json", out / "cloaking_exposure.png", tables / "e11_cloaking.tex"):
        path.unlink(missing_ok=True)
    artifacts = out / "artifacts"
    manifest = {"version": "E11-1", "seed": seed, "scenarios": list(SCENARIOS),
                "sites": [asdict(s) for s in sites], "collectors": [asdict(c) for c in COLLECTORS],
                "actions": [asdict(a) for a in ACTIONS], "budgets": list(budgets),
                "slot_seconds": SLOT_SECONDS, "slots": list(SLOTS),
                "ground_truth_definition": "any latent marker in the declared condition/time window; outages do not relabel truth",
                "network_mode": "emulated condition headers on loopback", "clock_mode": "scheduled logical slots",
                "collector_mode": "actual HTTP bytes with browser UA strings; no browser rendering"}
    (out / "schedule.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    grid, sweeps, observations, trials, contradictions = [], [], [], [], []
    with Testbed(sites) as server, closing(HTTPConnection("127.0.0.1", server.port, timeout=3)) as connection:
        for i, site in enumerate(sites):
            truth = {}
            # Independent evaluator measures ALL conditions. Results are withheld
            # from run_trial/select_action and do not count toward policy costs.
            for action in ACTIONS:
                c = COLLECTOR_MAP[action.collector_id]
                expected = site_state(site, c.user_agent, c.network, action.slot)
                probe = collect(server.port, site.host, action, f"truth:{site.site_id}:{action.action_id}", artifacts, connection)
                sweeps.append(probe)
                cell = {"site_id": site.site_id, "scenario": site.scenario, "action_id": action.action_id,
                        "slot": action.slot, "collector_id": c.collector_id, **expected,
                        "measured_available": probe["available"], "probe_observation_id": probe["observation_id"],
                        "body_sha256": probe["body_sha256"]}
                truth[action.action_id] = cell
                grid.append(cell)
            for budget in budgets:
                for policy in POLICIES:
                    history = run_trial(server.port, site.host, policy, budget, seed + i * 1009, artifacts, connection)
                    observations.extend(history)
                    row, pairs = evaluate_trial(site, history, truth, policy, budget)
                    trials.append(row)
                    contradictions.extend(pairs)
        server_log = list(server.request_log)
    errors = validate_observations(sweeps + observations, server_log, artifacts)
    for cell in grid:
        if cell["available"] != cell["measured_available"]:
            errors.append(f"{cell['site_id']}:{cell['action_id']}:unexpected_source_availability")
    for row in trials:
        if row["total_cost"] > row["budget"] or (row["available_observations"] == 0 and row["final_decision"] != "abstain"):
            errors.append(f"{row['site_id']}:{row['policy']}:budget_or_missingness")
        if row["false_contradiction_pairs"]:
            errors.append(f"{row['site_id']}:{row['policy']}:false_contradiction")
    summaries = [{"budget": b, "policy": p, **summarize([r for r in trials if r["budget"] == b and r["policy"] == p])}
                 for b in budgets for p in POLICIES]
    scenario_summary = [{"budget": b, "policy": p, "scenario": s,
                         **summarize([r for r in trials if r["budget"] == b and r["policy"] == p and r["scenario"] == s])}
                        for b in budgets for p in POLICIES for s in SCENARIOS]
    paired = []
    lookup = {(r["site_id"], r["budget"], r["policy"]): r for r in trials}
    for row in trials:
        base = lookup[row["site_id"], row["budget"], "fixed_three"]
        paired.append({"site_id": row["site_id"], "budget": row["budget"], "policy": row["policy"],
                       "reference": "fixed_three", "correctness_delta": int(row["correct_final"]) - int(base["correct_final"]),
                       "exposure_delta": int(row["cloaking_exposed"]) - int(base["cloaking_exposed"]),
                       "cost_delta": row["total_cost"] - base["total_cost"],
                       "same_actual_cost": row["total_cost"] == base["total_cost"]})
    controls = {
        "correlated_collectors_share_roots": COLLECTORS[0].ancestors == COLLECTORS[1].ancestors,
        "all_missing_trials_abstain": all(r["final_decision"] == "abstain" for r in trials if not r["available_observations"]),
        "benign_hash_variation_not_contradiction": all(r["true_contradiction_pairs"] == 0 and not r["false_positive"]
                                                       for r in trials if r["scenario"].startswith("benign")),
        "temporal_change_not_simultaneous_contradiction": all(r["true_contradiction_pairs"] == 0 for r in trials if r["scenario"] == "temporal_change"),
        "outage_hidden_markers_not_credited": all(not r["marker_discovered"] for r in trials if r["scenario"] in {"targeted_outage", "full_outage"}),
        "all_costs_within_budget": all(r["total_cost"] <= r["budget"] for r in trials),
        "responses_match_server_truth_and_hashes": not errors,
    }
    audit = {"audit_version": "E11-1", "world_type": "controlled_loopback_http_with_emulated_network_and_time",
             "seed": seed, "sites": len(sites), "sites_per_scenario": n_per, "scenarios": len(SCENARIOS),
             "policy_trials": len(trials), "budgets": list(budgets), "policies": list(POLICIES),
             "runtime_seconds": time.perf_counter() - started, "schedule_sha256": digest((out / "schedule.json").read_bytes()),
             "evaluation_probe_cost": len(sweeps), "evaluation_probe_http_requests": sum(o["http_requests"] for o in sweeps),
             "policy_acquisition_cost": sum(o["acquisition_cost"] for o in observations),
             "policy_http_requests": sum(o["http_requests"] for o in observations),
             "physical_client_connections": len({(r["peer_ip"], r["peer_port"]) for r in server_log}),
             "transport_failures": sum(o["status"] is None for o in sweeps + observations),
             "ground_truth": "server schedule and actual response receipts; withheld from policies; no model labels",
             "decision_rule": "any acquired marker => malicious; otherwise an acquired benign template => benign; only missing => abstain",
             "contradiction_rule": "opposite semantic states at the same scheduled slot, validated against both available server states",
             "cost_rule": "one unit per collection attempt including failures; redirects also reported as HTTP requests; all policies have the same cap",
             "time_rule": "logical slot wait plus 1 modeled second per attempt; actual HTTP wall latency separately measured; misses are censored, never zero",
             "cer_rule": "50/50 hypothetical witness outcomes, certificate interval/decision change and condition novelty per cost/wait; heuristic only",
             "limitations": ["No real network, mobile device, rendered-browser or field phishing performance is measured.",
                             "A benign observed template does not certify the absence of unobserved cloaking.",
                             "One-vantage stops at one and fixed-three at three; compare recorded actual costs as well as common ceilings.",
                             "Replicates share rule families; they are not independent real campaigns or a held-out generalization study.",
                             "Marker parsing is exact by construction; zero false positives is a fixture control, not detector accuracy."],
             "summary": summaries, "controls": controls, "violations": errors,
             "pass_criteria": {"status": "pass" if not errors and all(controls.values()) else "fail",
                               "gains_checked_against_controlled_truth_and_availability": not errors}}
    for name, rows in (("ground_truth.jsonl", grid), ("truth_probes.jsonl", sweeps),
                       ("observations.jsonl", observations), ("server_requests.jsonl", server_log),
                       ("contradictions.jsonl", contradictions)):
        _write_jsonl(out / name, rows)
    _write_csv(out / "trial_results.csv", trials)
    _write_csv(out / "summary.csv", summaries)
    _write_csv(out / "scenario_summary.csv", scenario_summary)
    _write_csv(out / "paired_comparisons.csv", paired)
    (out / "audit.json").write_text(json.dumps(audit, indent=2, allow_nan=False), encoding="utf-8")
    if audit["pass_criteria"]["status"] != "pass":
        # Remove only known generated publication artifacts from earlier runs.
        for path in (out / "cloaking_exposure.png", tables / "e11_cloaking.tex"):
            path.unlink(missing_ok=True)
        raise AssertionError(f"E11 integrity audit failed: {errors[:5]}")
    _write_table(tables / "e11_cloaking.tex", summaries)
    if plots:
        _plot(out / "cloaking_exposure.png", summaries)
    files = [p for p in out.rglob("*") if p.is_file() and p.name != "manifest_sha256.json"]
    (out / "manifest_sha256.json").write_text(json.dumps({str(p.relative_to(out)): digest(p.read_bytes()) for p in sorted(files)}, indent=2), encoding="utf-8")
    return audit


def _write_table(path: Path, rows: list[dict]):
    lines = ["% Controlled loopback HTTP; emulated network/time. Not field performance.",
             r"\begin{tabular}{lrllll}", r"Policy & Budget & Exposure & Repair & FP & Cost \\", r"\hline"]
    def fmt(value):
        return "--" if value is None else f"{value:.3f}"
    for r in rows:
        name = r["policy"].replace("_", r"\_")
        lines.append(f"{name} & {r['budget']} & {fmt(r['cloaking_exposure_rate'])} & {fmt(r['repair_success_rate'])} & {fmt(r['false_positive_rate'])} & {r['mean_cost']:.1f} " + r"\\")
    path.write_text("\n".join(lines + [r"\end{tabular}", ""]), encoding="utf-8")


def _plot(path: Path, rows: list[dict]):
    import matplotlib
